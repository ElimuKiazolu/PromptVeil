/**
 * Generates src/core/detect/validators/phone-shares.generated.ts: for every
 * libphonenumber region and every candidate length (7–15 digits), how many
 * of SAMPLES seeded random digit strings libphonenumber-js (max metadata)
 * accepts as a valid national number of that region, and the cell's class.
 *
 * A cell is "permissive" when the lower bound of the 99 % Wilson score
 * interval of that share is above 50 %: most random digit runs of that
 * length are valid numbers there, so validity alone proves little (Germany
 * at every length). Cells whose interval contains 50 % are near the line and
 * are not permissive.
 *
 * Run only after upgrading libphonenumber-js:
 *
 *   npm run generate:phone-shares
 *
 * If any cell changes class, the script lists the changes and writes
 * nothing; review them, then run again with --accept-class-changes.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  getCountries,
  parsePhoneNumberFromString,
} from 'libphonenumber-js/max';

const SAMPLES = 5000;
const LENGTHS = [7, 8, 9, 10, 11, 12, 13, 14, 15];
const SEED = 20261026;
/** Two-sided 99 % normal quantile. */
const Z = 2.5758;

const OUTPUT = fileURLToPath(
  new URL(
    '../src/core/detect/validators/phone-shares.generated.ts',
    import.meta.url,
  ),
);

function libraryVersion(): string {
  const packageJson: unknown = JSON.parse(
    readFileSync(
      fileURLToPath(
        new URL(
          '../node_modules/libphonenumber-js/package.json',
          import.meta.url,
        ),
      ),
      'utf8',
    ),
  );
  if (
    typeof packageJson === 'object' &&
    packageJson !== null &&
    'version' in packageJson &&
    typeof packageJson.version === 'string'
  ) {
    return packageJson.version;
  }
  throw new Error('libphonenumber-js version not found');
}

/** Lower bound of the Wilson score interval for `valid` of `samples`. */
export function wilsonLower(valid: number, samples: number): number {
  const p = valid / samples;
  const z2 = Z * Z;
  const centre = p + z2 / (2 * samples);
  const margin =
    Z * Math.sqrt((p * (1 - p)) / samples + z2 / (4 * samples * samples));
  return (centre - margin) / (1 + z2 / samples);
}

/** Region@length keys of the permissive cells in the current file, if any. */
function previousPermissive(): Set<string> | null {
  if (!existsSync(OUTPUT)) return null;
  const match = /PERMISSIVE_CELLS: readonly string\[\] = \[([^\]]*)\]/u.exec(
    readFileSync(OUTPUT, 'utf8'),
  );
  if (match === null) return null;
  return new Set((match[1] ?? '').match(/[A-Z0-9]+@\d+/gu) ?? []);
}

let state = SEED;
const next = (): number => {
  state = (state * 1103515245 + 12345) % 2147483648;
  return state / 2147483648;
};

const started = performance.now();
const rows: string[] = [];
const permissive: string[] = [];
const nearLine: string[] = [];
for (const region of getCountries()) {
  const counts: number[] = [];
  for (const length of LENGTHS) {
    let valid = 0;
    for (let i = 0; i < SAMPLES; i += 1) {
      let digits = '';
      for (let k = 0; k < length; k += 1) {
        digits += Math.floor(next() * 10).toString();
      }
      const phone = parsePhoneNumberFromString(digits, {
        defaultCountry: region,
        extract: false,
      });
      if (phone?.isValid() === true) valid += 1;
    }
    counts.push(valid);
    const lower = wilsonLower(valid, SAMPLES);
    const upper = 1 - wilsonLower(SAMPLES - valid, SAMPLES);
    if (lower > 0.5) permissive.push(`${region}@${length.toString()}`);
    else if (upper >= 0.5) nearLine.push(`${region}@${length.toString()}`);
  }
  rows.push(`  ${region}: [${counts.join(', ')}],`);
}

const before = previousPermissive();
if (before !== null) {
  const now = new Set(permissive);
  const added = permissive.filter((cell) => !before.has(cell));
  const removed = [...before].filter((cell) => !now.has(cell));
  if (
    (added.length > 0 || removed.length > 0) &&
    !process.argv.includes('--accept-class-changes')
  ) {
    console.error(
      `Class changes need review; nothing written.\n  now permissive: ${added.join(' ') || '(none)'}\n  no longer permissive: ${removed.join(' ') || '(none)'}\nRun again with --accept-class-changes once reviewed.`,
    );
    process.exit(1);
  }
}

const output = `// Generated by scripts/generate-phone-shares.ts; do not edit.
// For each libphonenumber region and length, how many of the samples
// (seeded random digit strings) libphonenumber-js (max) accepts as a valid
// national number, and the cells classed permissive (99 % Wilson lower
// bound of the share above 50 %).

export const PHONE_SHARES_LIBRARY_VERSION = '${libraryVersion()}';
export const PHONE_SHARES_SAMPLES = ${SAMPLES.toString()};
export const PHONE_SHARES_LENGTHS: readonly number[] = [${LENGTHS.join(', ')}];

export const PHONE_VALID_COUNTS: Readonly<Record<string, readonly number[]>> = {
${rows.join('\n')}
};

/** Reviewed classification snapshot: region@length of the permissive cells. */
export const PERMISSIVE_CELLS: readonly string[] = [${permissive.map((cell) => `'${cell}'`).join(', ')}];
`;
writeFileSync(OUTPUT, output);
console.log(
  `${rows.length.toString()} regions × ${LENGTHS.length.toString()} lengths × ${SAMPLES.toString()} samples, ${((performance.now() - started) / 1000).toFixed(0)} s`,
);
console.log(
  `permissive (${permissive.length.toString()}): ${permissive.join(' ')}`,
);
console.log(
  `near the line (${nearLine.length.toString()}): ${nearLine.join(' ')}`,
);
